// Generates src/tables.ts from the KTUG tables in data/. Run with `bun run tables`.
import { readFileSync, writeFileSync } from 'node:fs';

type Row = { from: number[]; to: number[]; legacy: boolean };

function readTable(name: string): Row[] {
  const rows: Row[] = [];
  for (const raw of readFileSync(new URL(`../data/${name}`, import.meta.url), 'utf8').split('\n')) {
    const line = raw.split('%')[0]!.trim();
    if (!line) continue;
    const [from, to] = line.split('=>') as [string, string];
    const codes = (side: string) =>
      side
        .trim()
        .split(/\s+/)
        .filter(Boolean)
        .map((code) => Number.parseInt(code.slice(2), 16));
    rows.push({ from: codes(from), to: codes(to), legacy: raw.includes('legacy encoding') });
  }
  return rows;
}

const escape = (codes: number[]) =>
  codes.map((code) => `\\u${code.toString(16).toUpperCase().padStart(4, '0')}`).join('');

const hanyang = readTable('hypua2jamocomposed.txt');

// The map composes in steps (ᄀ+ᄀ → ᄁ, ᄁ+ᄉ → …), so each cluster is reduced to its
// single letters here, which lets one lookup replace the chain of steps. A cluster can
// have several spellings: since Unicode 5.2 ᆼ+ᆨ and ᇰ+ᆨ both give U+11EC.
const composition = readTable('jamocompose.map');
const stepsOf = new Map<number, number[][]>();
// Legacy spellings sort last, so a cluster's first spelling is its current one.
for (const { from, to } of [...composition].sort((a, b) => Number(a.legacy) - Number(b.legacy))) {
  const steps = stepsOf.get(to[0]!) ?? [];
  steps.push(from);
  stepsOf.set(to[0]!, steps);
}
function spellings(code: number): number[][] {
  const steps = stepsOf.get(code);
  if (!steps) return [[code]];
  const all = steps.flatMap((step) =>
    step
      .map(spellings)
      .reduce<number[][]>(
        (prefixes, options) =>
          prefixes.flatMap((prefix) => options.map((option) => [...prefix, ...option])),
        [[]],
      ),
  );
  return [...new Map(all.map((spelling) => [spelling.join(), spelling])).values()];
}

const inRange = (code: number, ...ranges: [number, number][]) =>
  ranges.some(([low, high]) => low <= code && code <= high);
const clustersOf = (...ranges: [number, number][]) =>
  [...stepsOf.keys()]
    .filter((code) => inRange(code, ...ranges))
    .sort((a, b) => a - b)
    .flatMap((code) => spellings(code).map((spelling) => escape([code, ...spelling])))
    .join('|');

const source = `// Generated by scripts/build-tables.ts from data/. Do not edit.

/** Every Hanyang PUA code point followed by its conjoining jamo, in code point order. */
export const HANYANG: string = '${hanyang.map(({ from, to }) => escape([...from, ...to])).join('')}';

/** Jamo clusters, each followed by one spelling in single letters, separated by |. */
export const LEAD_CLUSTERS: string = '${clustersOf([0x1100, 0x115f], [0xa960, 0xa97c])}';
export const VOWEL_CLUSTERS: string = '${clustersOf([0x1160, 0x11a7], [0xd7b0, 0xd7c6])}';
export const TAIL_CLUSTERS: string = '${clustersOf([0x11a8, 0x11ff], [0xd7cb, 0xd7fb])}';
`;
writeFileSync(new URL('../src/tables.ts', import.meta.url), source);
console.log(`${hanyang.length} Hanyang rows, ${stepsOf.size} clusters`);
